package orm

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"unicode"
)

const (
	elasticsearchFieldsPackage = "esfields"
	elasticsearchImport        = "github.com/DropletLive/orm/elasticsearch"
	elasticsearchPackage       = "elasticsearch"
)

func (g *codeGenerator) generateElasticsearchDocuments(documents []*elasticsearchDocumentSchema) error {
	dir := filepath.Join(g.dir, elasticsearchFieldsPackage)
	if err := removeFiles(dir); err != nil {
		return err
	}
	if len(documents) == 0 {
		return nil
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("cannot create %s: %w", dir, err)
	}
	for _, document := range documents {
		source, err := format.Source(g.renderElasticsearchDocument(document))
		if err != nil {
			return fmt.Errorf("cannot format elasticsearch fields for %s: %w", document.name, err)
		}
		path := filepath.Join(dir, toSnakeCase(document.name)+".go")
		if err = os.WriteFile(path, source, 0644); err != nil {
			return fmt.Errorf("cannot write %s: %w", path, err)
		}
	}
	return nil
}

func removeFiles(dir string) error {
	files, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("cannot read directory %s: %w", dir, err)
	}
	for _, file := range files {
		if file.IsDir() {
			continue
		}
		if err = os.Remove(filepath.Join(dir, file.Name())); err != nil {
			return fmt.Errorf("cannot remove file %s: %w", file.Name(), err)
		}
	}
	return nil
}

func (g *codeGenerator) renderElasticsearchDocument(document *elasticsearchDocumentSchema) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by orm. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "package %s\n\n", elasticsearchFieldsPackage)
	buf.WriteString("import (\n")
	fmt.Fprintf(&buf, "\t%q\n", elasticsearchImport)
	if usesElasticsearchEnums(document.fields) {
		fmt.Fprintf(&buf, "\t%q\n", g.enumsImport)
	}
	buf.WriteString(")\n\n")
	fmt.Fprintf(&buf, "var %sFields = struct {\n%s}{\n%s}\n\n", document.name,
		elasticsearchFieldsStruct(document.fields, 1), elasticsearchFieldsInit(document.fields, "", 1))
	fmt.Fprintf(&buf, "var %sProperties = map[string]any{\n", document.name)
	writeElasticsearchProperties(&buf, document.fields, 1)
	buf.WriteString("}\n")
	return buf.Bytes()
}

func usesElasticsearchEnums(fields []*elasticsearchField) bool {
	for _, f := range fields {
		if f.tag.kind == elasticsearchKindEnum || usesElasticsearchEnums(f.children) {
			return true
		}
	}
	return false
}

func isElasticsearchContainer(f *elasticsearchField) bool {
	return f.tag.kind == elasticsearchKindNested || f.tag.kind == elasticsearchKindObject
}

func elasticsearchFieldsStruct(fields []*elasticsearchField, indent int) string {
	var buf bytes.Buffer
	tabs := strings.Repeat("\t", indent)
	for _, f := range fields {
		if isElasticsearchContainer(f) {
			fmt.Fprintf(&buf, "%s%s struct {\n%s%s}\n", tabs, f.goName, elasticsearchFieldsStruct(f.children, indent+1), tabs)
			continue
		}
		fmt.Fprintf(&buf, "%s%s %s\n", tabs, f.goName, elasticsearchFieldType(f))
	}
	return buf.String()
}

func elasticsearchFieldsInit(fields []*elasticsearchField, prefix string, indent int) string {
	var buf bytes.Buffer
	tabs := strings.Repeat("\t", indent)
	inner := strings.Repeat("\t", indent+1)
	for _, f := range fields {
		path := f.jsonName
		if prefix != "" {
			path = prefix + "." + f.jsonName
		}
		if isElasticsearchContainer(f) {
			fmt.Fprintf(&buf, "%s%s: struct {\n%s%s}{\n%s%s},\n", tabs, f.goName,
				elasticsearchFieldsStruct(f.children, indent+2), inner, elasticsearchFieldsInit(f.children, path, indent+2), inner)
			continue
		}
		fmt.Fprintf(&buf, "%s%s: %q,\n", tabs, f.goName, path)
	}
	return buf.String()
}

func elasticsearchFieldType(f *elasticsearchField) string {
	switch f.tag.kind {
	case elasticsearchKindText:
		return elasticsearchPackage + ".TextField"
	case elasticsearchKindEnum:
		return elasticsearchPackage + ".EnumField[" + f.tag.enumType + "]"
	case elasticsearchKindKeyword:
		return elasticsearchPackage + ".StringField"
	case elasticsearchKindFloat:
		return elasticsearchPackage + ".FloatField"
	}
	if f.goType == timeType {
		return elasticsearchPackage + ".DateField"
	}
	switch f.goType.Kind() {
	case reflect.Uint64:
		return elasticsearchPackage + ".UintField"
	case reflect.Int, reflect.Int64:
		return elasticsearchPackage + ".IntField"
	case reflect.Bool:
		return elasticsearchPackage + ".BoolField"
	case reflect.Float64:
		return elasticsearchPackage + ".FloatField"
	default:
		return elasticsearchPackage + ".StringField"
	}
}

func elasticsearchMappingType(f *elasticsearchField) string {
	switch f.tag.kind {
	case elasticsearchKindText:
		return "text"
	case elasticsearchKindEnum, elasticsearchKindKeyword:
		return "keyword"
	case elasticsearchKindFloat:
		return "float"
	}
	if f.goType == timeType {
		return "date"
	}
	switch f.goType.Kind() {
	case reflect.Uint64, reflect.Int64:
		return "long"
	case reflect.Int:
		return "integer"
	case reflect.Bool:
		return "boolean"
	case reflect.Float64:
		return "float"
	default:
		return "keyword"
	}
}

func writeElasticsearchProperties(buf *bytes.Buffer, fields []*elasticsearchField, indent int) {
	tabs := strings.Repeat("\t", indent)
	for _, f := range fields {
		switch f.tag.kind {
		case elasticsearchKindNested, elasticsearchKindObject:
			fmt.Fprintf(buf, "%s%q: map[string]any{\n", tabs, f.jsonName)
			if f.tag.kind == elasticsearchKindNested {
				fmt.Fprintf(buf, "%s\t\"type\": \"nested\",\n", tabs)
			}
			fmt.Fprintf(buf, "%s\t\"properties\": map[string]any{\n", tabs)
			writeElasticsearchProperties(buf, f.children, indent+2)
			fmt.Fprintf(buf, "%s\t},\n", tabs)
			fmt.Fprintf(buf, "%s},\n", tabs)
		case elasticsearchKindText:
			writeElasticsearchTextProperty(buf, f, tabs)
		default:
			fmt.Fprintf(buf, "%s%q: map[string]any{\"type\": %q},\n", tabs, f.jsonName, elasticsearchMappingType(f))
		}
	}
}

func writeElasticsearchTextProperty(buf *bytes.Buffer, f *elasticsearchField, tabs string) {
	tag := f.tag
	fmt.Fprintf(buf, "%s%q: map[string]any{\n", tabs, f.jsonName)
	fmt.Fprintf(buf, "%s\t\"type\": \"text\",\n", tabs)
	if tag.analyzer != "" {
		fmt.Fprintf(buf, "%s\t\"analyzer\": %q,\n", tabs, tag.analyzer)
	}
	if tag.searchAnalyzer != "" {
		fmt.Fprintf(buf, "%s\t\"search_analyzer\": %q,\n", tabs, tag.searchAnalyzer)
	}
	if tag.analyzer != "" || tag.autocomplete != "" || len(tag.subFields) > 0 {
		fmt.Fprintf(buf, "%s\t\"fields\": map[string]any{\n", tabs)
		if tag.analyzer != "" {
			fmt.Fprintf(buf, "%s\t\t\"keyword\": map[string]any{\"type\": \"keyword\"},\n", tabs)
		}
		if tag.autocomplete != "" {
			searchAnalyzer := tag.analyzer
			if tag.autocompleteSearch != "" {
				searchAnalyzer = tag.autocompleteSearch
			}
			fmt.Fprintf(buf, "%s\t\t\"autocomplete\": map[string]any{\n", tabs)
			fmt.Fprintf(buf, "%s\t\t\t\"type\":            \"text\",\n", tabs)
			fmt.Fprintf(buf, "%s\t\t\t\"analyzer\":        %q,\n", tabs, tag.autocomplete)
			fmt.Fprintf(buf, "%s\t\t\t\"search_analyzer\": %q,\n", tabs, searchAnalyzer)
			fmt.Fprintf(buf, "%s\t\t},\n", tabs)
		}
		for _, sub := range tag.subFields {
			fmt.Fprintf(buf, "%s\t\t%q: map[string]any{\n", tabs, sub.name)
			fmt.Fprintf(buf, "%s\t\t\t\"type\": \"text\",\n", tabs)
			if sub.analyzer != "" {
				fmt.Fprintf(buf, "%s\t\t\t\"analyzer\": %q,\n", tabs, sub.analyzer)
			}
			if sub.searchAnalyzer != "" {
				fmt.Fprintf(buf, "%s\t\t\t\"search_analyzer\": %q,\n", tabs, sub.searchAnalyzer)
			}
			fmt.Fprintf(buf, "%s\t\t},\n", tabs)
		}
		fmt.Fprintf(buf, "%s\t},\n", tabs)
	}
	fmt.Fprintf(buf, "%s},\n", tabs)
}

func toSnakeCase(s string) string {
	var result strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				result.WriteRune('_')
			}
			result.WriteRune(unicode.ToLower(r))
			continue
		}
		result.WriteRune(r)
	}
	return result.String()
}
